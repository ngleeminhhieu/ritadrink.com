export default function AwardsModule() {
  const popup = document.querySelector(".awardPopupJS");
  if (!popup) return;

  const header = document.querySelector(".hd");
  const cards = [...document.querySelectorAll(".awardOpenJS")];
  const shotEl = popup.querySelector(".awardShotJS");
  const tagEl = popup.querySelector(".awardTagJS");
  const eventEl = popup.querySelector(".awardEventJS");
  const awardEl = popup.querySelector(".awardAwardJS");
  const productEl = popup.querySelector(".awardProductJS");
  const descEl = popup.querySelector(".awardDescJS");
  const videoEl = popup.querySelector(".awardVideoJS");
  const alsoTrack = popup.querySelector(".awardAlsoTrackJS");
  let currentKey = "";
  let opener = null;
  let slider = null;

  const buildAlso = (activeKey) => {
    alsoTrack.innerHTML = Object.keys(AWARDS)
      .filter((key) => key !== activeKey)
      .map((key) => {
        const item = AWARDS[key];
        return `<div class="swiper-slide"><button class="award-popup__also-item awardSwitchJS" type="button" data-award="${key}" aria-label="عرض ${item.product}"><span class="award-popup__also-frame"><img src="${item.shot}" alt="" loading="lazy"></span></button></div>`;
      })
      .join("");
  };

  const syncSlider = () => {
    if (typeof window.Swiper !== "function") return;

    // Rebuilt slides only need a re-measure; re-creating the instance on every
    // switch makes the panel jump.
    if (slider) {
      slider.update();
      slider.slideTo(0, 0);
      return;
    }

    slider = new window.Swiper(popup.querySelector(".awardAlsoJS"), {
      slidesPerView: 1.6,
      spaceBetween: 0,
      speed: 600,
      grabCursor: true,
      watchOverflow: true,
      keyboard: {
        enabled: true,
        onlyInViewport: true,
      },
      breakpoints: {
        600: {
          slidesPerView: 2.4,
        },
        901: {
          slidesPerView: 3,
        },
      },
      a11y: {
        enabled: true,
        prevSlideMessage: "المنتج السابق",
        nextSlideMessage: "المنتج التالي",
        slideLabelMessage: "{{index}} من {{slidesLength}}",
      },
    });
  };

  const render = (key) => {
    const award = AWARDS[key];
    if (!award) return;

    currentKey = key;
    shotEl.src = award.shot;
    shotEl.alt = award.alt;
    tagEl.innerHTML = `<img src="${award.flag}" alt="" aria-hidden="true"><span>${award.city}</span>`;
    eventEl.textContent = award.event;
    awardEl.textContent = award.award;
    productEl.textContent = award.product;
    descEl.textContent = award.desc;

    // Only some awards ship a product film.
    if (videoEl) {
      videoEl.hidden = !award.video;
      if (award.video) videoEl.href = award.video;
      else videoEl.removeAttribute("href");
    }

    buildAlso(key);
    syncSlider();
  };

  // Open first, then render: Swiper measures wrong while the panel has no layout.
  const open = (key, trigger) => {
    document.dispatchEvent(new CustomEvent("panel:open", { detail: "award-popup" }));
    opener = trigger || null;
    popup.classList.add("is-open");
    popup.setAttribute("aria-hidden", "false");
    popup.removeAttribute("inert");
    document.body.classList.add("no-scroll");
    render(key);
    window.setTimeout(() => popup.querySelector(".awardCloseJS")?.focus({ preventScroll: true }), 180);
  };

  const close = ({ restoreFocus = true } = {}) => {
    if (!popup.classList.contains("is-open")) return;

    popup.classList.remove("is-open");
    popup.setAttribute("aria-hidden", "true");
    popup.setAttribute("inert", "");
    document.body.classList.remove("no-scroll");

    if (restoreFocus && opener?.isConnected) {
      opener.focus({ preventScroll: true });
    }
    opener = null;
  };

  cards.forEach((card) => {
    card.addEventListener("click", () => open(card.dataset.award, card));
  });

  popup.querySelectorAll(".awardCloseJS").forEach((button) => {
    button.addEventListener("click", () => close());
  });

  alsoTrack.addEventListener("click", (event) => {
    const item = event.target.closest(".awardSwitchJS");
    if (item && item.dataset.award !== currentKey) render(item.dataset.award);
  });

  // Hand over to the header opener so its scroll lock, focus and aria stay in sync.
  popup.querySelector(".awardCtaJS")?.addEventListener("click", () => {
    close({ restoreFocus: false });
    window.requestAnimationFrame(() => {
      header?.querySelector('[data-header-action-open="contact"]')?.click();
    });
  });

  document.addEventListener("panel:open", (event) => {
    if (event.detail !== "award-popup") close({ restoreFocus: false });
  });

  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape" && popup.classList.contains("is-open")) {
      event.preventDefault();
      close();
    }
  });
}
